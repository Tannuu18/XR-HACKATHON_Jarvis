// Development QA; requires Playwright, not an estimator dependency.
const { chromium } = require('playwright');
const { pathToFileURL } = require('url');
const path = require('path');
const fs = require('fs');
(async () => {
  const root = path.resolve(__dirname, '..');
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root, 'demo/index.html')).href);
  await page.locator('#play').click();
  await page.waitForTimeout(300);
  await page.locator('#play').click();
  if (await page.locator('#elapsed').textContent() === '0.000 s') throw Error('Playback did not advance');
  await page.locator('#scrub').fill('950');
  await page.locator('#scrub').dispatchEvent('input');
  if (await page.locator('#state').textContent() !== 'Blind prediction') throw Error('Blind status missing');
  await page.screenshot({ path: path.join(root, 'docs/viewer-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(root, 'docs/viewer-mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw Error('Mobile horizontal overflow');
  await page.locator('#upload').setInputFiles(path.join(root, 'reports/mh01_degraded.txt'));
  await page.waitForFunction(() => document.getElementById('dataset').textContent.includes('35,629'));
  if (await page.locator('#state').textContent() !== 'Loaded trajectory') throw Error('Incorrect uploaded status');
  const invalid = path.join(root, 'reports/viewer-invalid-fixture.txt');
  fs.writeFileSync(invalid, '1 2 nan\n');
  await page.locator('#upload').setInputFiles(invalid);
  await page.waitForFunction(() => document.getElementById('message').className === 'error');
  fs.unlinkSync(invalid);
  await browser.close();
  if (errors.length) throw Error(errors.join('\n'));
  console.log('Viewer passed: playback, blind status, desktop/mobile render, local upload, invalid-file handling; no console exceptions.');
})().catch(e => { console.error(e); process.exitCode = 1; });
